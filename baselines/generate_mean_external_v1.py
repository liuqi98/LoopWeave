"""Generate MEAN's five sampled H3 designs for the locked 20-sample external cohort.

CPU only (this host has no GPU). The generation recipe is the archived one:
one deterministic greedy MEAN backbone draw, plus five categorical sequence
samples drawn from the same reported logits with temperature 0.5 and the CPU
``torch.Generator().manual_seed(2026)`` stream.

The target-free context adapter (``convert`` + ``sanitize_input``) and the
generation-time sanitiser are not re-typed here: their exact source text is
read from the archived files and executed, so this script cannot silently
drift from the code that produced the archived MEAN results.  Running with
``--positive-control`` (default) additionally rebuilds the archived internal
MEAN test split and checks it against the archived rows and generations.

Nothing existing is modified: the output directory is created with
``exist_ok=False`` and the script aborts if it already exists.
"""
